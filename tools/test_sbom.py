# Unit tests for sbom.py: lockfile parsing, components and deterministic output.
#   python3 -m unittest tools/test_sbom.py
import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sbom  # noqa: E402

PUB = """# Generated by pub
packages:
  args:
    dependency: transitive
    description:
      name: args
      sha256: "abc123"
      url: "https://pub.dev"
    source: hosted
    version: "2.7.0"
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
  lepic:
    dependency: "direct main"
    description:
      path: "third_party/lepic-flutter"
      relative: true
    source: path
    version: "0.1.0"
sdks:
  dart: ">=3.9.0 <4.0.0"
"""

CARGO = """version = 4

[[package]]
name = "lepic-wallet"
version = "0.1.0"

[[package]]
name = "zeroize"
version = "1.8.1"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "ced3678a2879b30306d323f4542626697a464a97c0a07c9aebf7ebca65cd4dde"

[[package]]
name = "secp256k1zkp"
version = "0.7.13"
source = "git+https://github.com/EpicCash/rust-secp256k1-zkp?rev=42fcb29#42fcb29abc"
"""


class SbomTest(unittest.TestCase):
    def test_pub_packages(self):
        pkgs = {p["name"]: p for p in sbom.pub_packages(PUB)}
        self.assertEqual(set(pkgs), {"args", "flutter", "lepic"})
        self.assertEqual(pkgs["args"]["version"], "2.7.0")
        self.assertEqual(pkgs["args"]["sha256"], "abc123")
        self.assertEqual(pkgs["flutter"]["source"], "sdk")

    def test_cargo_skips_workspace_crates(self):
        names = [p["name"] for p in sbom.cargo_packages(CARGO)]
        self.assertEqual(names, ["secp256k1zkp", "zeroize"])

    def test_components(self):
        doc = sbom.sbom("26.11.0", PUB, CARGO, "04f6b912", "4018951")
        by = {c["bom-ref"]: c for c in doc["components"]}
        self.assertEqual(by["pub:args@2.7.0"]["hashes"][0]["content"], "abc123")
        self.assertEqual(by["cargo:zeroize@1.8.1"]["purl"], "pkg:cargo/zeroize@1.8.1")
        self.assertIn("rev=42fcb29", by["cargo:secp256k1zkp@0.7.13"]["externalReferences"][0]["url"])
        self.assertEqual(doc["metadata"]["component"]["version"], "26.11.0")
        self.assertNotIn("timestamp", doc["metadata"])

    def test_deterministic(self):
        a = json.dumps(sbom.sbom("26.11.0", PUB, CARGO, epoch="1761800000"), sort_keys=True)
        b = json.dumps(sbom.sbom("26.11.0", PUB, CARGO, epoch="1761800000"), sort_keys=True)
        self.assertEqual(a, b)
        self.assertTrue(json.loads(a)["serialNumber"].startswith("urn:uuid:"))

    def test_bad_version(self):
        with self.assertRaises(SystemExit):
            sbom.main(["--version", "1.2", "--out", "-"])


if __name__ == "__main__":
    unittest.main()
